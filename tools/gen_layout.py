#!/usr/bin/env python3
"""Write the game's layout, from the reverse engineering database in re/, as a C++ header.

The recomp's own code (recomp/src) reads and changes the game's memory through it: the
structures' fields with their types, the functions' and globals' addresses, and where each
overlay is loaded and its ID. recomp/src/game.hpp has the functions that use it.

usage: gen_layout.py REPO OUT.hpp
"""
import sys
from pathlib import Path

PRIMITIVES = {
    "u8": "std::uint8_t", "s8": "std::int8_t", "char": "char",
    "u16": "std::uint16_t", "s16": "std::int16_t",
    "u32": "std::uint32_t", "s32": "std::int32_t", "f32": "float",
}


def rows(path):
    """The lines of a TSV file in re/, without comments and blank lines, split on tabs."""
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cells = [cell.strip() for cell in line.split("\t")]
        out.append(cells + [""] * (5 - len(cells)))
    return out


def comment(text):
    return f"  // {text}" if text else ""


def cpp_type(text, structs):
    """The C++ type of a field or global."""
    text = text.strip()
    if text.endswith("*"):
        inner = text[:-1].strip()
        return f"Pointer<{'void' if inner == 'void' else cpp_type(inner, structs)}>"
    if text.endswith("]"):
        open_ = text.rindex("[")
        return f"Array<{cpp_type(text[:open_], structs)}, {int(text[open_ + 1:-1], 0)}>"
    if text in PRIMITIVES:
        return PRIMITIVES[text]
    if text == "vec3":
        return "Vec3"
    if text in structs:
        return text
    sys.exit(f"unknown type {text}")


def check_signature(name, signature, structs):
    """Exits unless the signature reads as "ret name(type a, type b)" with known types, as
    ghidra_scripts/ApplySymbols.java reads it (it stops at the first it can't, naming nothing)."""
    open_, close = signature.find("("), signature.rfind(")")
    head = signature[:open_].strip()
    if open_ < 0 or close < open_ or " " not in head or head.endswith("*"):
        sys.exit(f"{name}: can't read the signature {signature}")
    types = [head[:head.rindex(" ")]]
    params = signature[open_ + 1:close].strip()
    if params and params != "void":
        for param in params.split(","):
            param = " ".join(param.replace("*", "* ").split())
            if " " not in param:
                sys.exit(f"{name}: a parameter without a type or name in {signature}")
            types.append(param[:param.rindex(" ")].replace(" ", ""))
    for type_ in types:
        base = type_.rstrip("*").strip()
        if base not in PRIMITIVES and base not in ("void", "vec3") and base not in structs:
            sys.exit(f"{name}: unknown type {type_} in {signature}")


SIZES = {"u8": 1, "s8": 1, "char": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4, "vec3": 12}


def type_size(text, structs):
    """How many bytes a field of the type takes."""
    text = text.strip()
    if text.endswith("*"):
        return 4
    if text.endswith("]"):
        open_ = text.rindex("[")
        return type_size(text[:open_], structs) * int(text[open_ + 1:-1], 0)
    if text in SIZES:
        return SIZES[text]
    if text in structs and structs[text]["size"]:
        return structs[text]["size"]
    sys.exit(f"the size of {text} isn't known: give it a size row")


def structures(repo):
    structs = {}  # name: {"size", "base", "fields": [(offset, type, name, notes)]}
    for name, offset, type_, field, notes in rows(repo / "re/structs.tsv"):
        struct = structs.setdefault(name, {"size": 0, "base": None, "fields": []})
        if type_ == "size":
            struct["size"] = int(offset, 0)
        elif field == "base":
            if int(offset, 0) != 0:
                sys.exit(f"{name}: a base must be at 0")
            struct["base"] = type_
        else:
            struct["fields"].append((int(offset, 0), type_, field, notes))
    # Bases and the structures fields are made of come first.
    order, seen = [], set()

    def visit(name, depth=0):
        if name in seen:
            return
        if depth > 16:
            sys.exit(f"structures refer to each other in a loop at {name}")
        needs = [structs[name]["base"]] if structs[name]["base"] else []
        for _, type_, _, _ in structs[name]["fields"]:
            inner = type_.split("[")[0].strip()
            if inner in structs and not type_.endswith("*"):
                needs.append(inner)
        for need in needs:
            visit(need, depth + 1)
        seen.add(name)
        order.append(name)

    for name in structs:
        visit(name)
    return structs, order


def main(repo, out):
    repo = Path(repo)
    structs, order = structures(repo)
    lines = [
        "// Generated by tools/gen_layout.py from re/*.tsv and symbols/overlays.tsv: edit those.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace mhfu::game {",
        "",
        "// An address in the game's memory.",
        "using Address = std::uint32_t;",
        "",
        "struct Vec3 {",
        "  float x, y, z;",
        "};",
        "",
        "// A pointer in the game's memory to a T (an address).",
        "template <typename T>",
        "struct Pointer {",
        "  static constexpr std::uint32_t size = 4;",
        "};",
        "",
        "// How many bytes a type takes in the game's memory.",
        "template <typename T>",
        "inline constexpr std::uint32_t size_of = T::size;",
        "template <> inline constexpr std::uint32_t size_of<std::uint8_t> = 1;",
        "template <> inline constexpr std::uint32_t size_of<std::int8_t> = 1;",
        "template <> inline constexpr std::uint32_t size_of<char> = 1;",
        "template <> inline constexpr std::uint32_t size_of<std::uint16_t> = 2;",
        "template <> inline constexpr std::uint32_t size_of<std::int16_t> = 2;",
        "template <> inline constexpr std::uint32_t size_of<std::uint32_t> = 4;",
        "template <> inline constexpr std::uint32_t size_of<std::int32_t> = 4;",
        "template <> inline constexpr std::uint32_t size_of<float> = 4;",
        "template <> inline constexpr std::uint32_t size_of<Vec3> = 12;",
        "",
        "// A field of the structure Owner (or of one it is based on), of type T.",
        "template <typename Owner, typename T>",
        "struct Field {",
        "  using owner = Owner;",
        "  using type = T;",
        "  std::uint32_t offset;",
        "  // The field's place in a structure at `object`.",
        "  constexpr Address in(Address object) const { return object + offset; }",
        "};",
        "",
        "// N of T one after the other.",
        "template <typename T, std::uint32_t N>",
        "struct Array {",
        "  static constexpr std::uint32_t size = N * size_of<T>;",
        "};",
        "",
        "// Element `i` of an array field.",
        "template <typename Owner, typename T, std::uint32_t N>",
        "constexpr Field<Owner, T> at(Field<Owner, Array<T, N>> array, std::uint32_t i) {",
        "  return {array.offset + i * size_of<T>};",
        "}",
        "",
        "// A variable at a fixed address.",
        "template <typename T>",
        "struct Global {",
        "  using type = T;",
        "  Address address;",
        "};",
        "",
        "// Code loaded from DATA.BIN at `address`; its header holds its ID.",
        "struct Overlay {",
        "  Address address;",
        "  std::uint32_t id;",
        "};",
        "",
        "// A function of an overlay: only there while the overlay is loaded.",
        "struct OverlayFunction {",
        "  Overlay overlay;",
        "  Address address;",
        "};",
        "",
        "// --- Structures (re/structs.tsv). Steps are per 30 fps frame. ---",
        "",
    ]
    lines += [f"struct {name};" for name in order]
    for name in order:
        struct = structs[name]
        base = f" : {struct['base']}" if struct["base"] else ""
        # Without a size of its own: as far as its fields or its base go.
        size = struct["size"]
        if not size:
            ends = [structs[struct["base"]]["size"] if struct["base"] else 0]
            ends += [offset + type_size(type_, structs) for offset, type_, _, _ in struct["fields"]]
            size = max(ends)
        lines.append("")
        lines.append(f"struct {name}{base} {{")
        lines.append(f"  static constexpr std::uint32_t size = {size:#x};")
        names = set()
        for offset, type_, field, notes in sorted(struct["fields"]):
            if field in names or field == "size":
                sys.exit(f"{name}.{field}: named twice")
            names.add(field)
            lines.append(f"  static constexpr Field<{name}, {cpp_type(type_, structs)}> {field}{{{offset:#x}}};"
                         + comment(notes))
        lines.append("};")

    lines += ["", "// --- Overlays (symbols/overlays.tsv; the ID is the position there, from 1). ---", ""]
    lines.append("namespace overlay {")
    overlays = {}
    table = Path(repo / "symbols/overlays.tsv").read_text().splitlines()[1:]
    for id_, line in enumerate(table, 1):
        file_name, address, _size = line.split("\t")
        if not file_name.endswith(".ovl"):
            continue
        overlay = file_name.removesuffix(".ovl")
        overlays[overlay] = (int(address, 16), id_)
        lines.append(f"inline constexpr Overlay {overlay}{{0x{int(address, 16):08x}, {id_}}};")
    lines.append("}  // namespace overlay")

    lines += ["", "// --- Functions (re/functions.tsv). ---"]
    by_module = {}
    for module, address, name, signature, notes in rows(repo / "re/functions.tsv"):
        by_module.setdefault(module, []).append((int(address, 0), name, signature, notes))
    for module, functions in by_module.items():
        lines.append("")
        lines.append(f"namespace {module} {{")
        for address, name, signature, notes in functions:
            if signature:
                check_signature(name, signature, structs)
            text = "; ".join(part for part in (signature, notes) if part)
            if module == "eboot":
                lines.append(f"inline constexpr Address {name} = 0x{address:08x};" + comment(text))
            else:
                if module not in overlays:
                    sys.exit(f"{name}: no overlay {module} in symbols/overlays.tsv")
                lines.append(f"inline constexpr OverlayFunction {name}{{overlay::{module}, 0x{address:08x}}};"
                             + comment(text))
        lines.append(f"}}  // namespace {module}")

    lines += ["", "// --- Globals (re/globals.tsv). ---", "", "namespace global {"]
    for address, name, type_, notes in (row[:4] for row in rows(repo / "re/globals.tsv")):
        lines.append(f"inline constexpr Global<{cpp_type(type_, structs)}> {name}{{{int(address, 0):#010x}}};"
                     + comment(notes))
    lines += ["}  // namespace global", "", "}  // namespace mhfu::game", ""]

    text = "\n".join(lines)
    out = Path(out)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
