#!/bin/sh
# Builds the recompiled MHFU for Linux.
#
# usage: recomp/build_linux.sh PSPRISM_DIR WORK_DIR PROGRAM
#   PSPRISM_DIR  psprism checkout with psprism-mhfu.patch applied and built (make)
#   WORK_DIR     where generated code, objects and the executable go
#   PROGRAM      the game's program, from the player's own disc (PSP_GAME/SYSDIR/BOOT.BIN; play.sh
#                gets it with find_game --program)
# HOST=sdl (default) builds the SDL2 + OpenGL ES host (needs libsdl2-dev, libgles-dev);
# HOST=headless builds the host without a window.
# Set TRACE=1 to add the jump trace from add_trace.py to the dispatcher.
set -eu
PSPRISM=$(cd "$1" && pwd)
WORK=$(mkdir -p "$2" && cd "$2" && pwd)
PROGRAM=$3
REPO=$(cd "$(dirname "$0")/.." && pwd)
OUT=$WORK/generated
OBJ=$WORK/obj
JOBS=$(nproc)
HOST=${HOST:-sdl}
case $HOST in
	sdl) HOST_SOURCE=host/sdl_gles.cpp; HOST_CFLAGS="$(sdl2-config --cflags) -DMHFU_HAS_SDL"; HOST_LIBS="$(sdl2-config --libs) -lGLESv2" ;;
	headless) HOST_SOURCE=host/linux_headless.cpp; HOST_CFLAGS=; HOST_LIBS= ;;
	*) echo "unknown HOST=$HOST" >&2; exit 1 ;;
esac

# FFmpeg decodes the game's videos (H.264). Without it they play black, with sound.
FFMPEG_CFLAGS=
FFMPEG_LIBS=
if pkg-config --exists libavcodec libavformat libavutil libswscale 2>/dev/null; then
	FFMPEG_CFLAGS="-DREFRACT_HAS_FFMPEG=1 $(pkg-config --cflags libavcodec libavformat libavutil libswscale)"
	FFMPEG_LIBS=$(pkg-config --libs libavcodec libavformat libavutil libswscale)
else
	echo "FFmpeg development files not found: videos will be black" >&2
fi

# The game's program, translated to C++; recomp/mhfu.map says where its functions are.
rm -rf "$OUT"
"$PSPRISM/build/bin/psprism" "$PROGRAM" --output-dir "$OUT" --code-map "$REPO/recomp/mhfu.map"
if [ "${TRACE:-0}" = 1 ]; then python3 -I "$REPO/recomp/add_trace.py" "$OUT/dispatch.cpp"; fi

CXX="g++ -std=c++20 -O2 -pthread"
INC="-I$OUT -I$PSPRISM/include -I$PSPRISM/refract/include -I$PSPRISM/refract/include/pspsdk -I$PSPRISM/refract/src -I$PSPRISM/refract/third_party/at3_standalone $HOST_CFLAGS $FFMPEG_CFLAGS"
rm -rf "$OBJ" "$WORK/Resources" && mkdir -p "$OBJ" "$WORK/bin" "$WORK/Resources"
# The client for ad hoc servers (aemu_postoffice), for multiplayer: C, compiled on its own.
AEMU=$PSPRISM/refract/third_party/aemu_postoffice
for src in client/postoffice client/list client/sock_impl_linux client/postoffice_mem_stdc \
           client/enet adhocctl/client/adhocctl adhocctl/client/adhocctl_mem; do
	gcc -O2 -w -c "$AEMU/$src.c" -o "$OBJ/aemu_$(basename "$src").o"
done
# Its session with the server, host code: without the PSP SDK's headers, which stand in for the
# system's socket headers.
g++ -std=c++20 -O2 -pthread -I"$PSPRISM/refract/include" -c "$PSPRISM/refract/src/net/adhoc_control.cpp" \
	-o "$OBJ/adhoc_control.o"
{
	ls "$OUT"/native_unity_*.cpp "$OUT/dispatch.cpp"
	for src in runtime.cpp font/font_engine.cpp utility_data.cpp psp_sdk_bridge.cpp host/audio_engine.cpp \
	           host/common.cpp stubs/mpeg/media_engine.cpp $HOST_SOURCE; do
		echo "$PSPRISM/refract/src/$src"
	done
	echo "$AEMU/client/delay_impl_cpp.cpp"
	echo "$AEMU/client/mutex_impl_cpp.cpp"
	ls "$PSPRISM"/refract/third_party/at3_standalone/*.cpp
	echo "$OUT/platform/windows/platform.cpp"
	echo "$REPO/recomp/src/launcher.cpp"
	echo "$REPO/recomp/src/disc.cpp"
	echo "$REPO/recomp/src/camera.cpp"
	echo "$REPO/recomp/src/fps60.cpp"
	ls "$REPO"/recomp/src/features/*.cpp  # gameplay features (features.hpp)
} > "$OBJ/sources.txt"

# The build's revision, shown by the launcher.
mkdir -p "$WORK/config"
REVISION=$(git -C "$REPO" describe --always --dirty 2>/dev/null || echo unknown)
printf '// Generated by recomp/build_linux.sh.\n#pragma once\nnamespace mhfu {\ninline constexpr const char* build_revision = "%s";\n}\n' \
	"$REVISION" > "$WORK/config/launcher_config.hpp"
# The game's layout, by the names in re/, for the recomp's own code (recomp/src/game.hpp).
python3 -I "$REPO/tools/gen_layout.py" "$REPO" "$WORK/config/game_layout.hpp"
INC="$INC -I$WORK/config"
xargs -P "$JOBS" -I{} sh -c '$0 $1 -w -c {} -o "$2/$(echo {} | md5sum | cut -c1-12).o" || echo "FAILED {}"' \
	"$CXX" "$INC" "$OBJ" < "$OBJ/sources.txt"
$CXX -o "$WORK/bin/mhfu" "$OBJ"/*.o $HOST_LIBS $FFMPEG_LIBS
# Open fonts standing in for the PSP's system fonts (Liberation, SIL Open Font License).
# Distributions keep them in different places, so search the usual font directories.
FONTS=${FONTS:-/usr/share/fonts /usr/local/share/fonts $HOME/.local/share/fonts}
mkdir -p "$WORK/Resources/fonts"
for family in Sans Serif; do
	for style in Regular Bold Italic BoldItalic; do
		# shellcheck disable=SC2086
		font=$(find $FONTS -name "Liberation$family-$style.ttf" 2>/dev/null | head -n 1)
		if [ -z "$font" ]; then
			echo "Liberation$family-$style.ttf not found: install the Liberation fonts" >&2
			exit 1
		fi
		cp "$font" "$WORK/Resources/fonts/"
	done
done
# The launcher's headings: Cinzel (SIL Open Font License, recomp/fonts).
cp "$REPO/recomp/fonts/Cinzel-Bold.ttf" "$WORK/Resources/fonts/"
# The launcher's logo (recomp/art).
mkdir -p "$WORK/Resources/art"
cp "$REPO/recomp/art/logo.png" "$WORK/Resources/art/"
echo "built $WORK/bin/mhfu (run it, or: $WORK/bin/mhfu /path/to/game.iso)"
